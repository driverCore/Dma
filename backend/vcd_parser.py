"""
Fast, Cycle-Accurate VCD Waveform Parser for DMA Verification Lab (Phase 8)
Parses IEEE 1364 Value Change Dump (.vcd) files generated by Icarus Verilog,
extracts hardware bus signals, samples signals cycle-by-cycle, decodes FSM states,
and generates structured timeline JSON for frontend waveform visualization.
"""

import os
import re
from typing import Dict, List, Any, Optional

FSM_STATE_MAP = {
    0: "IDLE",
    1: "VALIDATE",
    2: "READ_REQ",
    3: "READ_WAIT",
    4: "WRITE_REQ",
    5: "WRITE_WAIT",
    6: "CHECK_DONE",
    7: "DONE",
    8: "ERROR"
}

ARB_GRANT_MAP = {
    0: "NONE",
    1: "DMA_M0",
    2: "EXT_M1",
    3: "RESERVED"
}

# Standard signals tracked for DMA Subsystem inspection
TRACKED_SIGNALS = {
    "clk": "clk",
    "rst_n": "rst_n",
    "debug_fsm_state": "fsm_state",
    "mem_req_valid": "req_valid",
    "mem_req_ready": "req_ready",
    "mem_req_rw": "req_rw",
    "mem_req_addr": "req_addr",
    "mem_rsp_valid": "rsp_valid",
    "mem_rsp_ready": "rsp_ready",
    "debug_fifo_occupancy": "fifo_occ",
    "debug_arb_grant": "arb_grant",
    "debug_bytes_done": "bytes_done",
    "ext_req": "ext_req",
    "ext_grant": "ext_grant",
    "irq": "irq",
    # Sub-block signals for FIFO & Arbiter
    "req0": "req0",
    "req1": "req1",
    "gnt0": "gnt0",
    "gnt1": "gnt1",
    "data_in": "data_in",
    "data_out": "data_out",
    "empty": "empty",
    "full": "full",
    "wr_en": "wr_en",
    "rd_en": "rd_en"
}

class VCDParser:
    @staticmethod
    def parse_header(vcd_path: str):
        """
        Parses the VCD header to extract timescale, variables, and identifiers.
        """
        timescale_ps = 1 # default 1ps
        id_to_signal = {}
        all_signals = []

        if not os.path.exists(vcd_path):
            return None, None, None

        with open(vcd_path, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if "$timescale" in line:
                    # Next line usually contains the timescale (e.g., 1ps or 1ns)
                    ts_line = f.readline().strip()
                    if "ns" in ts_line:
                        timescale_ps = 1000
                    elif "ps" in ts_line:
                        timescale_ps = 1
                elif line.startswith("$var"):
                    # Format: $var wire 1 ! mem_rsp_valid $end
                    # or:     $var wire 32 # mem_rsp_rdata [31:0] $end
                    parts = line.split()
                    if len(parts) >= 5:
                        var_id = parts[3]
                        var_name = parts[4]
                        # Strip array dimensions if present
                        base_name = var_name.split("[")[0].strip()
                        all_signals.append(base_name)
                        if base_name in TRACKED_SIGNALS and var_id not in id_to_signal:
                            id_to_signal[var_id] = {
                                "id": var_id,
                                "name": TRACKED_SIGNALS[base_name],
                                "orig_name": base_name,
                                "width": int(parts[2]) if parts[2].isdigit() else 1
                            }
                elif line.startswith("$enddefinitions"):
                    break

        return timescale_ps, id_to_signal, all_signals

    @classmethod
    def parse_waveform(
        cls,
        vcd_path: str,
        start_cycle: int = 0,
        cycle_count: int = 80,
        clock_period_ns: float = 10.0
    ) -> Dict[str, Any]:
        """
        Samples the VCD file cycle-by-cycle over a requested window.
        Returns timeline samples, landmarks, and signal states.
        """
        if not os.path.exists(vcd_path):
            raise FileNotFoundError(f"VCD file not found at: {vcd_path}")

        timescale_ps, id_to_signal, _ = cls.parse_header(vcd_path)
        if not id_to_signal:
            raise ValueError("No tracked signals found in VCD header.")

        # Clock period in VCD timestamp units
        # e.g., 10ns with timescale 1ps = 10000 timestamp units
        period_units = int((clock_period_ns * 1000) / timescale_ps)
        end_cycle = start_cycle + cycle_count
        start_time_unit = start_cycle * period_units
        end_time_unit = end_cycle * period_units

        # Initial values dict
        current_values = {}
        for sinfo in id_to_signal.values():
            sname = sinfo["name"]
            if sinfo["width"] == 1:
                current_values[sname] = 0
            else:
                current_values[sname] = "0x00000000" if "addr" in sname else 0

        # Data structure for recording cycle values
        samples_by_cycle = {}
        landmarks = []

        cur_timestamp = 0

        with open(vcd_path, "r", encoding="utf-8", errors="replace") as f:
            # Skip header
            for line in f:
                if line.startswith("$enddefinitions"):
                    break

            # Parse value changes
            for line in f:
                line = line.strip()
                if not line or line.startswith("$"):
                    continue

                if line.startswith("#"):
                    # Timestamp marker
                    try:
                        cur_timestamp = int(line[1:])
                    except ValueError:
                        continue

                    if cur_timestamp > end_time_unit:
                        break
                    continue

                # Parse scalar or vector change
                # Scalar: 0!, 1!, x!, z!
                # Vector: b0101 #, b1010101001010101 )
                if line.startswith("b") or line.startswith("B"):
                    parts = line.split()
                    if len(parts) >= 2:
                        raw_val = parts[0][1:]
                        var_id = parts[1]
                        if var_id in id_to_signal:
                            sinfo = id_to_signal[var_id]
                            sname = sinfo["name"]
                            try:
                                int_val = int(raw_val, 2)
                                if "addr" in sname:
                                    current_values[sname] = f"0x{int_val:08X}"
                                elif sname == "fsm_state":
                                    current_values[sname] = FSM_STATE_MAP.get(int_val, f"STATE_{int_val}")
                                elif sname == "arb_grant":
                                    current_values[sname] = ARB_GRANT_MAP.get(int_val, f"GRANT_{int_val}")
                                elif sname == "req_rw":
                                    current_values[sname] = "WRITE" if int_val == 1 else "READ"
                                else:
                                    current_values[sname] = int_val
                            except ValueError:
                                current_values[sname] = raw_val
                else:
                    # Single bit value change
                    val_char = line[0]
                    var_id = line[1:]
                    if var_id in id_to_signal:
                        sname = id_to_signal[var_id]["name"]
                        bit_val = 1 if val_char == "1" else 0
                        if sname == "req_rw":
                            current_values[sname] = "WRITE" if bit_val == 1 else "READ"
                        else:
                            current_values[sname] = bit_val

                # If current timestamp aligns with a cycle rising edge, record snapshot
                if cur_timestamp >= start_time_unit:
                    cyc = cur_timestamp // period_units
                    if start_cycle <= cyc <= end_cycle and cyc not in samples_by_cycle:
                        snapshot = current_values.copy()
                        samples_by_cycle[cyc] = snapshot

                        # Detect Key Engineering Landmarks
                        if snapshot.get("rst_n") == 1 and len(landmarks) == 0:
                            landmarks.append({"cycle": cyc, "label": "Reset Deasserted", "type": "info"})
                        if snapshot.get("fsm_state") == "READ_REQ" and not any(l["label"] == "Read Burst Start" for l in landmarks):
                            landmarks.append({"cycle": cyc, "label": "Read Burst Start", "type": "active"})
                        if snapshot.get("fsm_state") == "WRITE_REQ" and not any(l["label"] == "Write Burst Start" for l in landmarks):
                            landmarks.append({"cycle": cyc, "label": "Write Burst Start", "type": "active"})
                        if snapshot.get("irq") == 1 and not any(l["label"] == "Transfer Complete (IRQ)" for l in landmarks):
                            landmarks.append({"cycle": cyc, "label": "Transfer Complete (IRQ)", "type": "success"})
                        if snapshot.get("fsm_state") == "ERROR" and not any(l["label"] == "FSM Error State" for l in landmarks):
                            landmarks.append({"cycle": cyc, "label": "FSM Error State", "type": "error"})

        # Fill any gaps so every cycle in [start_cycle, end_cycle] has a sample
        timeline = []
        last_snap = current_values.copy()
        for c in range(start_cycle, end_cycle + 1):
            if c in samples_by_cycle:
                last_snap = samples_by_cycle[c]
            else:
                last_snap = last_snap.copy()
            timeline.append({
                "cycle": c,
                "time_ns": round(c * clock_period_ns, 1),
                "signals": last_snap
            })

        max_cycles = cur_timestamp // period_units if period_units > 0 else 0

        return {
            "vcd_file": os.path.basename(vcd_path),
            "clock_frequency_mhz": 100.0,
            "clock_period_ns": clock_period_ns,
            "total_cycles_in_vcd": max(max_cycles, len(timeline)),
            "window": {
                "start_cycle": start_cycle,
                "end_cycle": end_cycle,
                "count": len(timeline)
            },
            "landmarks": landmarks,
            "timeline": timeline
        }
